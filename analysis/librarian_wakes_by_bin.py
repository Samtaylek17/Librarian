from __future__ import annotations

import csv
import os
import statistics
from collections import defaultdict

import numpy as np

from _common import (
    AGENT_FAMILY, AGENT_ORDER, MODEL_DISPLAY, MODEL_ORDER, ROOT,
    iter_turn_rows, load_rows,
)

BIN_WIDTH = 32_000
BIN_CAP   = 96_000
LIB_AGENTS = [
    a for a in AGENT_ORDER
    if AGENT_FAMILY[a][1] and AGENT_FAMILY[a][0] in ("hyperagent", "boad")
]
ROW_LABEL_WAKE = {
    "HyperAgentLibrarianMASRunner":   "HyperAgent$+$Lib",
    "HyperAgentCavemanLibRunner":     "HyperAgent$+$Caveman$+$Lib",
    "BOADLibrarianMASRunner":         "BOAD$+$Lib",
    "BOADCavemanLibRunner":           "BOAD$+$Caveman$+$Lib",
}
TURNS_CSV = os.path.join(ROOT, "data", "turns.csv")
OUT_TEX = os.path.join(ROOT, "tables", "librarian_wakes_by_bin.tex")


def _compute_bins(rows):
    vanilla = [r for r in rows if r["agent"] == "VanillaRunner"]
    by_task = defaultdict(list)
    for r in vanilla:
        by_task[r["task_id"]].append(r["max_input_tokens"])
    task_diff = {t: statistics.mean(v) for t, v in by_task.items()}
    n_full = int(np.ceil(BIN_CAP / BIN_WIDTH))
    edges = [i * BIN_WIDTH for i in range(n_full + 1)] + [float("inf")]
    n_bins = n_full + 1
    task_bin = {}
    for t, d in task_diff.items():
        b = min(int(d // BIN_WIDTH), n_full)
        task_bin[t] = b
    return task_bin, edges, n_bins


def _bin_label(edges, i):
    lo = edges[i] / 1000.0
    hi = edges[i + 1]
    if hi == float("inf"):
        return f">{lo:.0f}K"
    return f"{lo:.0f}--{hi/1000:.0f}K"


def _is_lib(role: str) -> bool:
    return role == "navigator" or role.startswith("librarian")


def _wakes_per_episode() -> dict[tuple, list[int]]:
    per_ep: dict[tuple, list[tuple[int, str]]] = defaultdict(list)
    for r in iter_turn_rows():
        if r["agent_class"] not in LIB_AGENTS:
            continue
        key = (r["model"], r["agent_class"], r["task_id"], r["seed"])
        per_ep[key].append((int(r["turn_idx"]), r["agent_id"]))

    out: dict[tuple, list[int]] = {}
    for key, turns in per_ep.items():
        turns.sort()
        wakes: list[int] = []
        run = 0
        for _, role in turns:
            if _is_lib(role):
                run += 1
            else:
                if run:
                    wakes.append(run)
                    run = 0
        if run:
            wakes.append(run)
        out[key] = wakes
    return out


def main() -> None:
    rows = load_rows()
    task_bin, edges, n_bins = _compute_bins(rows)
    wakes_by_ep = _wakes_per_episode()

    agg: dict[tuple, list[int]] = defaultdict(list)
    for (model, agent, task_id, _seed), wakes in wakes_by_ep.items():
        b = task_bin.get(task_id)
        if b is None:
            continue
        agg[(model, agent, b)].append(len(wakes))

    bin_size = [sum(1 for v in task_bin.values() if v == b) for b in range(n_bins)]
    n_cols = 1 + n_bins

    lines = [
        "% Auto-generated by scripts/librarian_wakes_by_bin.py from data/turns.csv. Do not edit.",
        "\\setlength{\\tabcolsep}{6pt}",
        "\\renewcommand{\\arraystretch}{1.25}",
        "\\resizebox{\\linewidth}{!}{",
        "\\begin{tabular}{l" + "r" * n_bins + "}",
        "\\toprule",
        f"\\multicolumn{{1}}{{c}}{{}} & \\multicolumn{{{n_bins}}}{{c}}{{Reference max-input tokens (K)}} \\\\",
        f"\\cmidrule(lr){{2-{n_cols}}}",
        "\\multirow{2}{*}{Method} & "
        + " & ".join(_bin_label(edges, i) for i in range(n_bins)) + " \\\\",
        " & "
        + " & ".join(f"(n={bin_size[i]})" for i in range(n_bins)) + " \\\\",
        "\\midrule",
    ]
    fam_order: list[str] = []
    fam_to_agents: dict[str, list[str]] = {}
    for a in LIB_AGENTS:
        fam = AGENT_FAMILY[a][0]
        if fam not in fam_to_agents:
            fam_order.append(fam)
            fam_to_agents[fam] = []
        fam_to_agents[fam].append(a)

    for mi, model in enumerate(MODEL_ORDER):
        lines.append("\\rowcolor{gray!12}")
        lines.append(
            f"\\multicolumn{{{n_cols}}}{{l}}"
            f"{{\\textbf{{{MODEL_DISPLAY[model]}}}}} \\\\"
        )
        for fi, fam in enumerate(fam_order):
            for agent in fam_to_agents[fam]:
                cells = []
                for b in range(n_bins):
                    vals = agg.get((model, agent, b), [])
                    cells.append(f"{sum(vals)/len(vals):.2f}" if vals else "--")
                lines.append(f"{ROW_LABEL_WAKE[agent]} & " + " & ".join(cells) + " \\\\")
            if fi != len(fam_order) - 1:
                lines.append("\\midrule")
        if mi != len(MODEL_ORDER) - 1:
            lines.append("\\midrule")
    lines += [
        "\\bottomrule",
        "\\end{tabular}",
        "}",
    ]
    os.makedirs(os.path.dirname(OUT_TEX), exist_ok=True)
    with open(OUT_TEX, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {OUT_TEX}")

    print()
    print("Bin edges (K):", [f"{e/1000:.0f}" for e in edges])
    for model in MODEL_ORDER:
        print(f"\n[{MODEL_DISPLAY[model]}] mean wakes / episode")
        for agent in LIB_AGENTS:
            row = []
            for b in range(n_bins):
                vals = agg.get((model, agent, b), [])
                row.append(f"{sum(vals)/len(vals):5.2f}" if vals else "  -- ")
            print(f"  {agent:34s} " + " ".join(row))


if __name__ == "__main__":
    main()
